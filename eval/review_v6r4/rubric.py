"""Keep the round-4 rubric's rules identical to the prompt's.

    python eval/review_v6r4/rubric.py          # rewrite the generated part of RUBRIC.md
    python eval/review_v6r4/rubric.py --check  # exit 1 if RUBRIC.md is out of date

The judges must apply exactly the rules Haiku was given, so the rubric does not restate
them: the part of RUBRIC.md between the markers is the prompt's own text (the input rules
of comment mode, what counts, the fields, the levels, the rules, the checklist and the
examples), copied from eval/prompts/v6_common.py and v6_comment.py. v6_selftest fails when
the two drift apart.
"""

import importlib.util
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PROMPTS = os.path.join(os.path.dirname(HERE), "prompts")
RUBRIC = os.path.join(HERE, "RUBRIC.md")
BEGIN = "<!-- generated by eval/review_v6r4/rubric.py from the round-4 prompt; do not edit by hand -->"
END = "<!-- end of generated rules -->"


def _load(name):
    spec = importlib.util.spec_from_file_location(name, os.path.join(PROMPTS, name + ".py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def _section(text, tag):
    m = re.search(rf"<{tag}>\n(.*?)\n</{tag}>", text, re.S)
    return m.group(1)


def generated():
    c, pc = _load("v6_common"), _load("v6_comment")
    inp = _section(pc.SYSTEM_PROMPT, "input")
    parts = [BEGIN, "",
             "### Context and input (the model's `<input>`)", "", "```text", inp, "```", "",
             "### What counts (`<what_counts>`)", "", "```text", _section(c.SCOPE, "what_counts"), "```", "",
             "### Fields (`<fields>`)", "", "```text", _section(c.FIELDS, "fields"), "```", "",
             "### Levels (`<levels>`)", "", "```text", _section(c.SCALE, "levels"), "```", "",
             "### Rules (`<rules>`)", "", "```text", _section(c.RULES, "rules"), "```", "",
             "### The model's checklist (`<before_answering>`)", "", "```text",
             _section(c.CHECK, "before_answering"), "```", "",
             "### Worked examples (`<examples>`, invented places)", "", "```text",
             _section(c.EXAMPLES, "examples"), "```", "", END]
    return "\n".join(parts)


def current():
    s = open(RUBRIC, encoding="utf-8").read()
    return s, s.index(BEGIN), s.index(END) + len(END)


def main():
    s, i, j = current()
    new = s[:i] + generated() + s[j:]
    if "--check" in sys.argv:
        sys.exit(0 if new == s else 1)
    with open(RUBRIC, "w", encoding="utf-8") as f:
        f.write(new)
    print("RUBRIC.md rules regenerated" if new != s else "RUBRIC.md already current")


if __name__ == "__main__":
    main()

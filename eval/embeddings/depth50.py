"""Correct recall@50 for the depth-20 pool, by sampling.

The pool covers each system's top 20. Ranks 21-50 are judged only when another
system happened to rank the same comment in its own top 20, so a system whose
deeper results are *different* from everyone else's (Qwen: 62% of its top 50
judged, vs 75% for OpenAI-large) has more unjudged comments counted as
non-relevant. Recall@50 is the metric that matters most for this search
design (similarity picks which comments count; restaurants are then ranked by
distinct people), so the bias has to be measured rather than footnoted.

Judging every unjudged top-50 comment would be 10,530 more pairs. Instead:

    python depth50.py sample      # 150 unjudged pairs per system -> blind batches
    #   judges grade data/judging/comments_d50/batch_NNN.md per GUIDELINES.md
    python merge_judgments.py --tag comments_d50
    python depth50.py estimate    # -> DEPTH50.md

For each system, the sampled share of its unjudged top-50 comments judged >= 1
is the estimated relevance rate of all of them. Estimated relevant in top 50 =
judged relevant + rate x unjudged count. The denominator adds the same
correction to the pool: the union of all sampled systems' unjudged top-50
comments, at the pooled rate. The rates carry Wilson 95% intervals; with 150
samples per system they are about +-7 points.
"""

import json
import math
import random
import sys
from collections import defaultdict

from common import DATA, HERE, read_jsonl
from pool import write_batches

SYSTEMS = ["qwen3-8b", "oai-3-large", "gemini-2", "oai-3-small", "voyage-4-large", "bm25"]
PER_SYSTEM = 150
SEED = 5050
TAG = "comments_d50"


def unjudged_top50():
    judged = {(r["qid"], r["doc_id"]) for r in read_jsonl(HERE / "judgments_comments.jsonl")}
    out = {}
    for s in SYSTEMS:
        run = json.loads((DATA / "runs" / "full" / f"{s}.json").read_text())
        out[s] = sorted({(q, d) for q, lst in run.items() for d, _ in lst[:50] if (q, d) not in judged})
    return judged, out


def sample():
    rng = random.Random(SEED)
    _, unj = unjudged_top50()
    chosen = {s: rng.sample(unj[s], min(PER_SYSTEM, len(unj[s]))) for s in SYSTEMS}
    (HERE / "depth50_sample.json").write_text(json.dumps(chosen, indent=0))
    pairs = sorted({p for ps in chosen.values() for p in ps})
    queries = {q["qid"]: q for q in read_jsonl(HERE / "queries.jsonl")}
    docs = {r["id"]: r for r in read_jsonl(DATA / "corpus.jsonl")}
    outdir = DATA / "judging" / TAG
    outdir.mkdir(parents=True, exist_ok=True)
    n = write_batches(pairs, 240, "batch", outdir, queries, docs, "comments", rng)
    print(f"{len(pairs)} distinct pairs in {n} batches -> {outdir}")


def wilson(k, n, z=1.96):
    if n == 0:
        return (0.0, 0.0, 0.0)
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return p, c - h, c + h


def estimate():
    judged_rows = read_jsonl(HERE / "judgments_comments.jsonl")
    rel = defaultdict(dict)
    for r in judged_rows:
        rel[r["qid"]][r["doc_id"]] = r["grade"]
    extra = {(r["qid"], r["doc_id"]): r["grade"] for r in read_jsonl(HERE / f"judgments_{TAG}.jsonl")}
    chosen = {s: [tuple(p) for p in ps] for s, ps in json.loads((HERE / "depth50_sample.json").read_text()).items()}
    _, unj = unjudged_top50()

    rates = {}
    for s in SYSTEMS:
        g = [extra[p] for p in chosen[s] if p in extra]
        rates[s] = wilson(sum(1 for x in g if x >= 1), len(g)) + (len(g),)
    pooled_k = sum(1 for p, gr in extra.items() if gr >= 1)
    pooled_rate = pooled_k / len(extra)
    union_unj = set().union(*[set(unj[s]) for s in SYSTEMS])
    qids = sorted(rel)
    R_pool = sum(1 for q in qids for g in rel[q].values() if g >= 1)
    R_est = R_pool + pooled_rate * len(union_unj)

    lines = ["# Recall@50 corrected for pool depth\n",
             "Generated by `depth50.py`. The depth-20 pool leaves part of each system's top 50 unjudged; "
             "those comments count as non-relevant in RESULTS_TABLES_comments.md. Here a random 150 of each "
             "system's unjudged top-50 comments were judged blind (same guidelines, shuffled, no system "
             "labels), and the share judged >= 1 is used as that system's rate for all of its unjudged "
             "top-50 comments.\n",
             f"Pool relevant (judged >= 1): {R_pool:,}. Unjudged top-50 comments across these systems: "
             f"{len(union_unj):,}, sampled rate {pooled_rate*100:.0f}%, so estimated total relevant "
             f"{R_est:,.0f}. Micro-averaged over all 110 queries.\n",
             f"With ~{R_est / len(qids):.0f} relevant comments per query, a perfect top 50 would reach "
             f"recall@50 of about {100 * 50 * len(qids) / R_est:.0f}, so the estimated precision@50 column "
             "(estimated relevant in the top 50, divided by 50) is the easier one to read. Intervals cover "
             "only the sampling of unjudged comments, not the sampling of queries.\n",
             "| system | top-50 judged | unjudged in top 50 | rate among sampled unjudged [95% CI] | "
             "recall@50 as scored | recall@50 corrected [range from rate CI] | est. precision@50 |",
             "|---|---|---|---|---|---|---|"]
    for s in SYSTEMS:
        run = json.loads((DATA / "runs" / "full" / f"{s}.json").read_text())
        top = [(q, d) for q, lst in run.items() for d, _ in lst[:50]]
        judged_rel = sum(1 for q, d in top if rel[q].get(d, 0) >= 1)
        n_unj = len(unj[s])
        p, lo, hi, n = rates[s]
        as_scored = judged_rel / R_pool
        corr = (judged_rel + p * n_unj) / R_est
        c_lo = (judged_rel + lo * n_unj) / R_est
        c_hi = (judged_rel + hi * n_unj) / R_est
        lines.append(f"| {s} | {1 - n_unj / len(top):.0%} | {n_unj:,} | {p*100:.0f}% [{lo*100:.0f}, {hi*100:.0f}] (n={n}) | "
                     f"{as_scored*100:.1f} | **{corr*100:.1f}** [{c_lo*100:.1f}, {c_hi*100:.1f}] | "
                     f"{(judged_rel + p * n_unj) / len(top) * 100:.0f}% |")
    lines.append("\nThe as-scored column is micro-averaged against the pool's relevant count, so it differs "
                 "slightly from the per-query mean in the main table; compare systems within a column.")
    (HERE / "DEPTH50.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    {"sample": sample, "estimate": estimate}[sys.argv[1]]()
